import { P } from './kit';

export function mkFont(def, opt = {}) {
  const f = { g: {}, sp: opt.sp ?? 1, space: opt.space ?? 3, h: opt.h ?? 7, mono: opt.mono || 0 };
  for (const ch in def) {
    const rows = def[ch];
    let w = 0; for (const r of rows) w = Math.max(w, r.length);
    f.g[ch] = { w, rows };
  }
  return f;
}
